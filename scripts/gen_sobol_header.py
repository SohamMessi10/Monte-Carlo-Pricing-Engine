"""Generate cpp/include/mcpricer/sobol_directions.hpp from the Joe–Kuo direction numbers.

Input: new-joe-kuo-6.21201 from https://web.maths.unsw.edu.au/~fkuo/sobol/
Each data row is "d s a m_1 ... m_s": dimension d, degree s of its primitive polynomial, the
polynomial's inner coefficients a packed into an integer, and s initial direction integers.
Dimension 1 is not in the file; it is the van der Corput sequence (all m_i = 1).

Usage:
  python scripts/gen_sobol_header.py [--dims N] [--data PATH] [--license PATH] [--out PATH]
"""

import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE_URL = "https://web.maths.unsw.edu.au/~fkuo/sobol/new-joe-kuo-6.21201"


def read_rows(path, dims):
    """Rows for dimensions 2..dims, checked so a bad download or format fails loudly."""
    rows = []
    with open(path) as f:
        header = f.readline().split()
        if header[:3] != ["d", "s", "a"]:
            raise SystemExit(f"unexpected header in {path}: {header}")
        for line in f:
            if len(rows) == dims - 1:
                break
            d, s, a, *m = (int(x) for x in line.split())
            expected_d = len(rows) + 2
            if d != expected_d:
                raise SystemExit(f"expected dimension {expected_d}, found {d}")
            if len(m) != s:
                raise SystemExit(f"dimension {d}: degree {s} but {len(m)} direction integers")
            if not 0 <= a < 2 ** max(s - 1, 0):
                raise SystemExit(f"dimension {d}: a = {a} does not fit in s - 1 = {s - 1} bits")
            for i, m_i in enumerate(m, start=1):
                if m_i % 2 == 0 or m_i >= 2**i:
                    raise SystemExit(f"dimension {d}: m_{i} = {m_i} must be odd and < 2^{i}")
            rows.append((s, a, m))
    if len(rows) != dims - 1:
        raise SystemExit(f"{path} has only {len(rows) + 1} dimensions, {dims} requested")
    return rows


def render(rows, dims, license_text):
    notice = "\n".join(f"// {line}".rstrip() for line in license_text.strip().splitlines())
    primitives, initial_m = [], []
    for s, a, m in rows:
        primitives.append(f"    {{{s}, {a}, {len(initial_m)}}},")
        initial_m.extend(m)
    m_lines = [
        "    " + ", ".join(str(x) for x in initial_m[i : i + 16]) + ","
        for i in range(0, len(initial_m), 16)
    ]
    return "\n".join(
        [
            "// Sobol direction numbers: the first "
            f"{dims} dimensions of Joe and Kuo's new-joe-kuo-6.21201",
            f"// ({SOURCE_URL}).",
            "// Generated by scripts/gen_sobol_header.py. Do not edit by hand.",
            "//",
            "// License notice for the direction numbers:",
            "//",
            notice,
            "",
            "#pragma once",
            "",
            "#include <array>",
            "#include <cstdint>",
            "",
            "namespace mcpricer::sobol_data {",
            "",
            "// Degree s of the primitive polynomial, its packed inner coefficients a, and the",
            "// offset of its s initial direction integers m_1..m_s in kInitialM.",
            "struct Primitive {",
            "    std::uint32_t s;",
            "    std::uint32_t a;",
            "    std::uint32_t m_offset;",
            "};",
            "",
            "// Number of dimensions, including dimension 1 (van der Corput, not stored).",
            f"inline constexpr std::uint32_t kDims = {dims};",
            "",
            f"inline constexpr std::array<Primitive, {len(primitives)}> kPrimitives{{{{",
            *primitives,
            "}};",
            "",
            f"inline constexpr std::array<std::uint32_t, {len(initial_m)}> kInitialM{{{{",
            *m_lines,
            "}};",
            "",
            "}  // namespace mcpricer::sobol_data",
            "",
        ]
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--dims", type=int, default=1024)
    parser.add_argument(
        "--data", type=Path, default=ROOT / "third_party/joe-kuo/new-joe-kuo-6.21201"
    )
    parser.add_argument("--license", type=Path, default=ROOT / "third_party/joe-kuo/LICENSE")
    parser.add_argument(
        "--out", type=Path, default=ROOT / "cpp/include/mcpricer/sobol_directions.hpp"
    )
    args = parser.parse_args()
    if args.dims < 2:
        raise SystemExit("--dims must be at least 2")

    rows = read_rows(args.data, args.dims)
    args.out.write_text(render(rows, args.dims, args.license.read_text()))
    max_degree = max(s for s, _, _ in rows)
    print(f"wrote {args.out} ({args.dims} dimensions, max polynomial degree {max_degree})")


if __name__ == "__main__":
    main()
